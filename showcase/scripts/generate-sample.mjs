// Developer utility. Reads repository fixture constants; never imports PageTrace.
// Render builds consume the bundled files and do not need the parent repository.
import { writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { pages, examples, SOURCE_REVISION } from '../site/data.js';

const root = new URL('../../', import.meta.url);
const source = execFileSync('git', ['show', `${SOURCE_REVISION}:src/pagetrace/portfolio.py`], { cwd: root, encoding: 'utf8' });
const constants = source.match(/PORTFOLIO_PAGE_TEXTS = \(\r?\n([\s\S]*?)\r?\n\)/)?.[1];
if (!constants) throw new Error('Cannot find the documented fixture');
const texts = [...constants.matchAll(/"([^"\r\n]*)"/g)].map(match => match[1]);
if (JSON.stringify(texts) !== JSON.stringify(pages.map(page => page.text))) throw new Error('Fixture text drift');
for (const [constant, query] of [['ANSWER', examples[0].query], ['ABSTENTION', examples[2].query]]) {
  if (!source.includes(`PORTFOLIO_${constant}_QUESTION = "${query}"`)) throw new Error('Example question drift');
}
// Direct byte-format port of portfolio.py:_portfolio_pdf_bytes.
const fontId = 3 + 2 * texts.length;
const pageIds = texts.map((_, index) => 3 + 2 * index);
const objects = new Map([
  [1, '<< /Type /Catalog /Pages 2 0 R >>'],
  [2, `<< /Type /Pages /Kids [${pageIds.map(id => `${id} 0 R`).join(' ')}] /Count ${pageIds.length} >>`],
  [fontId, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>'],
]);
texts.forEach((text, index) => {
  if (/[^\x00-\x7f]/u.test(text)) throw new Error('Fixture requires ASCII');
  const escaped = text.replaceAll('\\', '\\\\').replaceAll('(', '\\(').replaceAll(')', '\\)');
  const content = `BT\n/F1 12 Tf\n72 720 Td\n(${escaped}) Tj\nET\n`;
  const pageId = pageIds[index];
  objects.set(pageId, `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 ${fontId} 0 R >> >> /Contents ${pageId + 1} 0 R >>`);
  objects.set(pageId + 1, `<< /Length ${Buffer.byteLength(content)} >>\nstream\n${content}endstream`);
});
let output = Buffer.from('%PDF-1.4\n%\xe2\xe3\xcf\xd3\n', 'latin1');
const offsets = [0];
for (let id = 1; id <= fontId; id++) {
  offsets.push(output.length);
  output = Buffer.concat([output, Buffer.from(`${id} 0 obj\n${objects.get(id)}\nendobj\n`, 'ascii')]);
}
const xrefOffset = output.length;
output = Buffer.concat([output, Buffer.from(`xref\n0 ${fontId + 1}\n0000000000 65535 f \n${offsets.slice(1).map(offset => `${String(offset).padStart(10, '0')} 00000 n \n`).join('')}trailer\n<< /Size ${fontId + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`, 'ascii')]);
const sha256 = value => createHash('sha256').update(value).digest('hex');
const pdfSha256 = sha256(output);
const directory = new URL('../site/samples/', import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL('northstar-fy2025.pdf', directory), output);
await writeFile(new URL('../site/sample-identity.js', import.meta.url), `// SHA-256 of the bundled deterministic source PDF, not a Python artifact ID.\nexport const pdfSha256 = '${pdfSha256}';\n`);
await writeFile(new URL('provenance.json', directory), JSON.stringify({
  type: 'pagetrace_static_demo_sample',
  synthetic: true,
  source_repository: 'https://github.com/HivMindAI/PageTrace',
  source_revision: SOURCE_REVISION,
  source_path: 'src/pagetrace/portfolio.py',
  source_constants: 'PORTFOLIO_PAGE_TEXTS',
  pdf_generator: '_portfolio_pdf_bytes (byte-format port; validated against original function)',
  pdf_sha256: pdfSha256,
  pdf_bytes: output.length,
  pages: pages.map(page => ({ ...page, text_sha256: sha256(page.text), reference_scope: 'demo-local; not a Python chunk ID' })),
  limitations: ['Bundled text is not extracted or OCR-processed by this website.', 'Reading-view headings are presentation only.', 'No canonical Python corpus, geometry, retrieval, QA, or quality artifact is generated by this website.'],
}, null, 2) + '\n');
console.log(`Bundled ${texts.length} synthetic pages; PDF SHA-256 ${pdfSha256}`);
